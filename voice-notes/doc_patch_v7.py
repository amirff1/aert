#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
doc_patch_v7 — وصلهٔ متنی «نسل هفت» (کانال کاهش نویز + رأی‌گیری وزنی)
====================================================================
  • پاراگراف «حقیقتِ روش» را با اعداد تازه به‌روز می‌کند
  • ردیف‌های نسل هفت را به پیوست ت (شفافیت) اضافه می‌کند
  • منابع متن خام را به v7 تغییر می‌دهد
اجرای دوباره بی‌خطر است (اگر نشانهٔ کار انجام‌شده باشد، دست نمی‌زند).
"""
from __future__ import annotations
import sys
from pathlib import Path

TRUTH = """**حقیقتِ روش:** هیچ مدل فارسیِ بهتری در این محیط قابل دریافت نبود؛ پس مسیر را از
> «مدلِ بزرگ‌تر» به «**شاهدِ بیشتر روی همان صدا**» عوض کردم و سه روش تازه افزودم:
> **(۱) رمزگشایی اجباری** با واژگانِ محدودشده به اصطلاح‌های ECG که واژه‌های انگلیسی
> (QRS، axis، gain، speed…) را از دلِ گفتارِ فارسی بیرون می‌کشد؛ **(۲) تطبیق آوایی** با
> دروازهٔ کم‌بسامدی برای پیشنهاد واژهٔ تخصصی؛ **(۳) بازبینی قانونیِ ۴۶۶ واژهٔ کم‌اطمینان**
> علیه همهٔ کانال‌های خام. رأی‌گیری روی ۱۰ کانال: **۹۲٫۲٪ واژه‌ها با ≥۲ رأی**،
> و **۱۲٫۹٪ واژه‌ها** همچنان کم‌اطمینان‌اند (‹› خورده‌اند). نتیجهٔ اصطلاح‌ها:
> **۲۱۲ شنیدهٔ تأییدشده با شاهدِ صوتیِ مستقل** (پیوست ث). متن خام کامل هر قطعه در
> `transcript-fa-v5.md` (خام) و `transcript-fa-v6-evidence.md` (خام + لایهٔ ≈ و ✔)
> و ابزارها در `voice-notes/` است. **برای استناد، فایل صوتی را بشنوید.**"""

TRUTH_V7 = """**حقیقتِ روش:** صدا با بهرهٔ خیلی کم ضبط شده (RMS ≈ −۵۰ dBFS) و هرچه قطعه آرام‌تر،
> خطای شنیدن بیشتر بود — پس مسیر را عوض کردم: **«تنظیم گوش» برای هر قطعه**. چهار کار تازه:
> **(۱) کانالِ گیتینگِ طیفی** (`noisereduce`) که در آزمونِ تنظیمِ گوش برندهٔ ۳ از ۶ قطعهٔ آرام شد؛
> **(۲) رمزگشایی اجباری** با واژگانِ محدود به اصطلاح‌های ECG (کشف QRS، axis، gain، speed…)؛
> **(۳) تطبیق آوایی** با دروازهٔ کم‌بسامدی؛ **(۴) رأی‌گیری وزنی** که وزن هر کانال را از توافقش
> با رأی اکثریت می‌گیرد. نتیجه روی **۱۲ کانال**: توافق ≥۲ رأی از ۹۲٫۲٪ به **۹۴٫۹٪** و
> واژه‌های کم‌اطمینان از ۱۲٫۹٪ به **۱۱٫۷٪** رسید (در قطعه‌های آرام مثل media1: ۳۶٪→۲۱٪،
> media29: ۱۸٪→۱۱٪). اصطلاح‌ها: **۴۶۰ شنیدهٔ تأییدشده** که پس از پالایش **۲۰۹** مورد با
> شاهدِ قوی در پیوست ث آمده. آزمونِ جایگشتی: ۲۴٫۱٪ در برابر ۳٫۹٪ِ تصادفی (**۶٫۱۵×**).
> متن خام کامل در `transcript-fa-v7.md` (خام) و `transcript-fa-v7-evidence.md` (با لایهٔ ≈ و ✔)
> و ابزارها در `voice-notes/` است. **برای استناد، فایل صوتی را بشنوید.**"""

ROWS = """| موتور صدا | ۶ جریان، رأی‌گیری | **۱۲ کانال + رأی‌گیری وزنی** |
| کانال تازهٔ نسل ۷ | — | **گیتینگِ طیفی (`noisereduce`)** برای هر قطعه — برندهٔ آزمون `fa_autotune.py` |
| وزنِ کانال‌ها | برابر | **وزنی**: وزن = توافق کانال با رأی اکثریت (v3: ۰٫۸۶ · speechnorm: ۰٫۷۵ · nr_fa042: ۰٫۷۴ …) |
| آزمونِ «تنظیم گوش» | نداشت | ۸ زنجیرهٔ پیش‌پردازش × ۶ قطعهٔ آرام → `autotune.json` |
| نتیجهٔ منفیِ ثبت‌شده | — | **تغییر گام صدا (VTLN): توافق ۰** و **PocketSphinx: ۱ از ۸** — هر دو کنار گذاشته شدند |"""


def main() -> None:
    path = Path(sys.argv[1] if len(sys.argv) > 1 else 'zadkamali/joze-kamel.md')
    s = path.read_text(encoding='utf-8')
    n = 0

    # پاراگراف حقیقتِ روش (نسخهٔ ششم یا هفتم)
    if '**حقیقتِ روش:** صدا با بهرهٔ خیلی کم' not in s:
        start = s.find('**حقیقتِ روش:**')
        if start >= 0:
            end = s.index('**برای استناد، فایل صوتی را بشنوید.**', start)
            end = s.index('\n', end)
            while s[end + 1:end + 2] == '>':
                end = s.index('\n', end + 1)
            s = s[:start] + TRUTH_V7 + s[end:]
            n += 1

    # ردیف‌های تازه در پیوست ت
    anchor = '| راستی‌آزمایی روش |'
    if 'کانال تازهٔ نسل ۷' not in s and anchor in s:
        s = s.replace(anchor, ROWS + '\n' + anchor, 1)
        n += 1

    # ارجاع به فایل‌های متن خام
    s = s.replace('`transcript-fa-v5.md` (خام) و `transcript-fa-v6-evidence.md` (خام + لایهٔ ≈ و ✔)',
                  '`transcript-fa-v7.md` (خام) و `transcript-fa-v7-evidence.md` (خام + لایهٔ ≈ و ✔)')
    # بازتولید در پیوست ت
    s = s.replace('python3 voice-notes/fa_pipeline5.py                        # ۴ کانال تازه + رأی‌گیری',
                  'python3 voice-notes/fa_pipeline7.py                        # کانال گیتینگِ طیفی (نو)\n'
                  '> python3 voice-notes/fa_merge_rover7.py                      # رأی‌گیری وزنی ۱۲ کاناله')
    path.write_text(s, encoding='utf-8')
    print(f'✓ {n} وصلهٔ نسل ۷ اعمال شد → {path}')


if __name__ == '__main__':
    main()
